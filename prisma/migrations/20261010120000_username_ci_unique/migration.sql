-- Ник уникален без учёта регистра на уровне БД: «Demo» и «demo» — одна учётка,
-- даже при одновременной регистрации (проверка в коде не спасает от гонки).
--
-- Функциональный индекс Prisma в schema.prisma не выражает, поэтому schema.prisma
-- не меняется: индекс живёт только в миграции. Нарушение приходит в Prisma как P2002
-- (регистрация отвечает общим 409 ACCOUNT_TAKEN).
--
-- Идемпотентно и без изменения данных. Если в базе уже есть ники, совпадающие без
-- учёта регистра, CREATE UNIQUE INDEX упадёт и миграция не применится — данные
-- при этом не трогаются (на проде таких пар 0, проверено перед выпуском).
CREATE UNIQUE INDEX IF NOT EXISTS "User_username_lower_key" ON "User" (lower("username"));
