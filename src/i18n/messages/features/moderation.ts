export type ModerationLocale = keyof typeof moderationMessages;

export function moderationText(locale: string) {
  return moderationMessages[locale === 'en' ? 'en' : 'ru'];
}

export function fillModeration(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
}
