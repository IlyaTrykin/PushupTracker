/** «245 ккал» / «3,4 ккал»: целые от 10, до 10 — с одним знаком. */
export function formatKcal(kcal: number, locale: 'ru' | 'en'): string {
  const value = kcal >= 10 ? Math.round(kcal) : Math.round(kcal * 10) / 10;
  return value.toLocaleString(locale === 'en' ? 'en-US' : 'ru-RU', { maximumFractionDigits: 1 });
}
