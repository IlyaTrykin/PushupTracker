export function fillGroupGoalTemplate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
}

export function groupGoalErrorText(locale: 'ru' | 'en', code: unknown): string {
  const errors: Record<string, string> = groupGoalMessages[locale].errors;
  return (typeof code === 'string' && errors[code]) || errors.save;
}
